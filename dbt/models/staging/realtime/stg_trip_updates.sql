-- One stop time update per TripUpdates snapshot (spec 6.1). A view: a filter
-- on snapshot_date reads only that date's files.
select
    header_ts,
    entity_id,
    is_deleted,
    trip__trip_id,
    trip__route_id,
    cast(trip__direction_id as integer) as trip__direction_id,
    trip__start_time,
    trip__start_date,
    trip__schedule_relationship,
    trip__modified_trip,
    vehicle__id,
    vehicle__label,
    vehicle__license_plate,
    vehicle__wheelchair_accessible,
    cast(stop_time_update__stop_sequence as integer) as stop_time_update__stop_sequence,
    stop_time_update__stop_id,
    stop_time_update__arrival.delay as stop_time_update__arrival__delay,
    stop_time_update__arrival.time as stop_time_update__arrival__time,
    stop_time_update__arrival.uncertainty as stop_time_update__arrival__uncertainty,
    stop_time_update__arrival.scheduled_time as stop_time_update__arrival__scheduled_time,
    stop_time_update__departure.delay as stop_time_update__departure__delay,
    stop_time_update__departure.time as stop_time_update__departure__time,
    stop_time_update__departure.uncertainty as stop_time_update__departure__uncertainty,
    stop_time_update__departure.scheduled_time as stop_time_update__departure__scheduled_time,
    stop_time_update__departure_occupancy_status,
    stop_time_update__schedule_relationship,
    stop_time_update__stop_time_properties,
    cast(timestamp as bigint) as timestamp,
    delay,
    trip_properties__trip_id,
    trip_properties__start_date,
    trip_properties__start_time,
    trip_properties__shape_id,
    trip_properties__trip_headsign,
    trip_properties__trip_short_name,
    date as snapshot_date,
    filename
from {{ source('silver', 'trip_updates') }}
